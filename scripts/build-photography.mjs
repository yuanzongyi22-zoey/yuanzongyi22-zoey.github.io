#!/usr/bin/env node
// Rebuilds the photo lists in src/photography-content.ts from the folders under
// public/photography/. Editorial copy already in the file is preserved: a set keeps
// its title / english / note / meta if a folder of the same name was there before.
//
//   public/photography/
//     portrait/<set folder>/*.jpg     one folder per shoot, one spread per folder
//     landscape/*.jpg                 one continuous run, filename order
//
// Usage: node scripts/build-photography.mjs

import { execFileSync } from 'node:child_process'
import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs'
import { join, relative } from 'node:path'

const root = process.cwd()
const base = join(root, 'public/photography')
const target = join(root, 'src/photography-content.ts')
const extensions = /\.(jpe?g|png|webp|avif|heic)$/i

const dimensions = file => {
  const out = execFileSync('sips', ['-g', 'pixelWidth', '-g', 'pixelHeight', file], { encoding: 'utf8' })
  const width = Number(out.match(/pixelWidth:\s*(\d+)/)?.[1])
  const height = Number(out.match(/pixelHeight:\s*(\d+)/)?.[1])
  if (!width || !height) throw new Error(`cannot read size of ${file}`)
  return { width, height }
}

const listImages = dir => {
  let entries = []
  try { entries = readdirSync(dir) } catch { return [] }
  return entries.filter(name => extensions.test(name)).sort((a, b) => a.localeCompare(b, 'en', { numeric: true }))
    .map(name => {
      const file = join(dir, name)
      const { width, height } = dimensions(file)
      // A `-film` suffix marks the frames that arrived in the 胶片 subfolder.
      const tag = /-film\./i.test(name) ? 'FILM' : undefined
      return { src: `/${relative(join(root, 'public'), file)}`, width, height, tag }
    })
}

const listFolders = dir => {
  try { return readdirSync(dir).filter(name => statSync(join(dir, name)).isDirectory()).sort((a, b) => a.localeCompare(b, 'en', { numeric: true })) } catch { return [] }
}

// Keep whatever copy the file already carries, keyed by folder name. The block runs
// from the id to its own `photos:`, so a `meta:` array in between is matched too.
const existing = readFileSync(target, 'utf8')
const copyFor = id => {
  const block = existing.match(new RegExp(`id: '${id}',(.*?)photos:`, 's'))?.[0] ?? ''
  const pick = key => block.match(new RegExp(`${key}: '((?:[^'\\\\]|\\\\.)*)'`))?.[1]
  const meta = block.match(/meta: \[(.*?)\]/s)?.[1]
  return { title: pick('title'), english: pick('english'), note: pick('note'), layout: pick('layout'), meta }
}

const quote = value => `'${String(value).replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`
const photoLines = photos => photos.map(photo => `      { src: ${quote(photo.src)}, width: ${photo.width}, height: ${photo.height}${photo.tag ? `, tag: ${quote(photo.tag)}` : ''} },`).join('\n')

const folders = listFolders(join(base, 'portrait'))
const sets = folders.map((folder, index) => {
  const photos = listImages(join(base, 'portrait', folder))
  const copy = copyFor(folder)
  const lines = [
    `  {`,
    `    id: ${quote(folder)}, index: ${quote(String(index + 1).padStart(2, '0'))},`,
    `    title: ${quote(copy.title ?? folder)}, english: ${quote(copy.english ?? folder)},`,
  ]
  if (copy.note) lines.push(`    note: ${quote(copy.note)},`)
  if (copy.layout) lines.push(`    layout: ${quote(copy.layout)},`)
  if (copy.meta) lines.push(`    meta: [${copy.meta}],`)
  lines.push(`    photos: [\n${photoLines(photos)}\n    ],`, `  },`)
  return { lines: lines.join('\n'), count: photos.length, folder }
})

const landscape = listImages(join(base, 'landscape'))
const runCopy = copyFor('landscape-run')

const file = `// Generated by scripts/build-photography.mjs from public/photography/.
// Editorial copy (title / english / note / meta / layout) is preserved across runs; rerun
// the script after adding or renaming photos. Hand-edit the copy here, not the paths.
// The layout helpers live in src/PhotographySection.tsx; this file is data only.

export type Photo = { src: string; width: number; height: number; alt?: string; tag?: string }
// A spread picks its collage template from the photo count unless \`layout\` overrides it.
export type FolioLayout = 'solo' | 'duo' | 'trio' | 'quad'
export type PortraitSet = {
  id: string
  index: string
  title: string
  english: string
  note?: string
  meta?: { label: string; value: string }[]
  layout?: FolioLayout
  photos: Photo[]
}
export type LandscapeRun = {
  id: string
  title: string
  english: string
  note?: string
  photos: Photo[]
}

export const portraitSets: PortraitSet[] = [
${sets.map(set => set.lines).join('\n')}
]

export const landscapeRun: LandscapeRun = {
  id: 'landscape-run',
  title: ${quote(runCopy.title ?? '风光')}, english: ${quote(runCopy.english ?? 'Landscapes')},
  note: ${quote(runCopy.note ?? '连续往下看，像翻一本摊开的影像集。')},
  photos: [
${photoLines(landscape)}
  ],
}
`

writeFileSync(target, file)
console.log(`portrait sets: ${sets.length}`)
sets.forEach(set => console.log(`  ${set.folder} — ${set.count} photos`))
console.log(`landscape run: ${landscape.length} photos`)
